-- Renders every app's config (and the wallpaper) from PALETTE and FONT.
-- ${name} placeholders come from PALETTE, FONT and VARS; ${rgb_name} gives "r,g,b" for KDE.
local HOME = os.getenv("HOME")

local function json(s) return (s:gsub("\\", "\\\\"):gsub('"', '\\"')) end
local function byte(hex, i) return tonumber(hex:sub(i, i + 1), 16) end
local function rgb(hex) return string.format("%d,%d,%d", byte(hex, 1), byte(hex, 3), byte(hex, 5)) end

local VARS = {
    power      = json(POWER_MENU),
    network    = json(APPS.network),
    mixer      = json(APPS.mixer),
    lock       = IDLE.lock,
    screen_off = IDLE.screen_off,
}

local function lookup(k)
    local base = k:match("^rgb_(.+)$")
    if base then return PALETTE[base] and rgb(PALETTE[base]) end
    local v = PALETTE[k] or FONT[k] or VARS[k]
    return v and tostring(v)
end

local changed = false
local function put(path, data)
    os.execute("mkdir -p '" .. path:match("^(.*)/") .. "'")
    local f = io.open(path, "rb")
    local old = f and f:read("*a")
    if f then f:close() end
    if old == data then return end
    f = io.open(path, "wb")
    if f then f:write(data); f:close(); changed = true end
end

local function render(rel, header, body)
    local text = header:format("generated by nothing-os from ~/.config/hypr/nothing; edit the Lua, not this file")
        .. "\n" .. body:gsub("%${([%w_]+)}", lookup)
    put(HOME .. "/.config/" .. rel, text)
end

---------------------------------------------------------------- wallpaper: Nothing dot grid
-- One anti-aliased dot per tile; swaybg tiles it across any screen size.
local function dot_tile(size, radius, fg, bg)
    local px, c = {}, (size - 1) / 2
    for y = 0, size - 1 do
        for x = 0, size - 1 do
            local a = math.max(0, math.min(1, radius + 0.5 - math.sqrt((x - c) ^ 2 + (y - c) ^ 2)))
            for i = 1, 5, 2 do
                px[#px + 1] = string.char(math.floor(byte(bg, i) + (byte(fg, i) - byte(bg, i)) * a + 0.5))
            end
        end
    end
    return string.format("P6\n%d %d\n255\n", size, size) .. table.concat(px)
end
put(WALLPAPER, dot_tile(28, 1.6, PALETTE.faint, PALETTE.black))

